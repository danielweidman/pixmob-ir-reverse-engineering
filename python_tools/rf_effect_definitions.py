# Light effect codes for the RF (Sub-GHz) PixMob bracelets. This is the Sub-GHz
# counterpart to effect_definitions.py, which holds the IR codes.
#
# Each effect is a list of 1s and 0s: the on/off state of the 915 MHz (USA) or 868 MHz
# (EU/UK) carrier at each ~510 microsecond step. Use rf_conversion_funcs.py to turn these
# into Flipper Zero .sub files, or rf_effects_to_flipper_files.py to generate a whole set
# at once.
#
# These were decoded from the captures in rf/edited_rf_captures/915Mhz/. Every code starts
# with the same 16-bit "1010101010101010" preamble, which the bracelets use to lock on.
#
# Unlike the IR codes, these are whole packets: there is no separate "tail code" that can
# be appended to change the fade behaviour, so the fade/blink variants are listed in full.

